using System.Text;
using CSharpUI.Avalonia.SourceGenerator.Analysis;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpUI.Avalonia.SourceGenerator.InternalGenerators;

public sealed class ControlFactoryGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var controlModels = context.CompilationProvider
            .Select(static (compilation, _) => GetEligibleControls(compilation));

        context.RegisterSourceOutput(controlModels, static (sourceContext, models) =>
        {
            if (models.Length == 0)
            {
                return;
            }

            sourceContext.AddSource("CSharpUIControlFactories.g.cs", SourceText.From(GenerateSource(models), Encoding.UTF8));
        });
    }

    private static ControlModel[] GetEligibleControls(Compilation compilation) =>
        [..
            SymbolUtilities.GetPublicClasses(compilation.Assembly.GlobalNamespace)
                .Concat(SymbolUtilities.GetTargetAssemblies(compilation)
                    .SelectMany(static target => SymbolUtilities.GetPublicClasses(target.Assembly.GlobalNamespace)))
                .Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)
                .Select(type => ControlModelBuilder.Build(type, compilation.Assembly))
                .Where(static model => !model.IgnoreGeneratedExtensions &&
                    model.GenerateFactory &&
                    model.IsConstructible &&
                    model.Type.IsOrInheritsFrom("Avalonia.Controls.Control") &&
                    model.Type.IsAccessibleFromGeneratedCode())
                .GroupBy(static model => SymbolUtilities.CleanIdentifier(model.FactoryName) ?? model.Type.Name, StringComparer.Ordinal)
                .Where(static group => group.Count() == 1)
                .Select(static group => group.First())
                .OrderBy(static model => model.Type.ToDisplayString(), StringComparer.Ordinal)
        ];

    private static string GenerateSource(IReadOnlyList<ControlModel> controlModels)
    {
        var source = new StringBuilder(4096);
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#pragma warning disable CS1591");
        source.AppendLine("#nullable enable");
        source.AppendLine("namespace CSharpUI.Avalonia;");
        source.AppendLine("internal static class GeneratedControlFactories");
        source.AppendLine("{");

        foreach (var model in controlModels)
        {
            var methodName = SymbolUtilities.CleanIdentifier(model.FactoryName) ?? model.Type.Name;
            var controlType = model.Type;
            var typeName = controlType.GetFullTypeName();
            source.AppendLine($"    public static {typeName} {methodName}([global::System.Runtime.CompilerServices.CallerFilePath] string? sourceFile = null, [global::System.Runtime.CompilerServices.CallerLineNumber] int sourceLine = 0)");
            source.AppendLine("    {");
            source.AppendLine($"        var control = new {typeName}();");
            source.AppendLine("        global::CSharpUI.Avalonia.SourceInfo.Set(control, sourceFile, sourceLine);");
            source.AppendLine("        return control;");
            source.AppendLine("    }");
        }

        source.AppendLine("}");
        return source.ToString();
    }
}
