using System;

namespace CSharpUI.Avalonia;

/// <summary>
/// Overrides how the source generator exposes a control or member.
/// </summary>
[AttributeUsage(
    AttributeTargets.Class | AttributeTargets.Property | AttributeTargets.Event | AttributeTargets.Field,
    AllowMultiple = false,
    Inherited = false)]
public sealed class CSharpUIGeneratorMetadataAttribute : Attribute
{
    /// <summary>
    /// Suppresses generated APIs for the annotated control or member.
    /// </summary>
    public bool Ignore { get; set; }

    /// <summary>
    /// Renames the generated control factory or fluent member method.
    /// </summary>
    public string? Alias { get; set; }

    /// <summary>
    /// Controls factory generation for a control. Factories are generated by default.
    /// </summary>
    public bool GenerateFactory { get; set; } = true;

    /// <summary>
    /// Marks a public property as the control's content slot for generated tooling metadata.
    /// </summary>
    public bool Content { get; set; }
}
